<?php

declare(strict_types=1);

namespace App\Deploy\Infrastructure\Caddy;

use App\Deploy\Domain\Model\DeployDomain;
use App\Deploy\Domain\ReverseProxyRouter;
use App\Shared\Infrastructure\Config\ServerSettings;
use Symfony\Component\DependencyInjection\Attribute\AsAlias;
use Symfony\Component\DependencyInjection\Attribute\Autowire;
use Symfony\Component\Filesystem\Filesystem;
use Symfony\Component\Process\ExecutableFinder;
use Symfony\Component\Process\Process;
use Symfony\Contracts\HttpClient\HttpClientInterface;

#[AsAlias(ReverseProxyRouter::class)]
final readonly class CaddyReverseProxyRouter implements ReverseProxyRouter
{
    public function __construct(
        private ServerSettings $settings,
        private HttpClientInterface $httpClient,
        #[Autowire('%kernel.project_dir%')]
        private string $projectDir,
        #[Autowire(env: 'default::CADDY_ADMIN_ADDR')]
        private ?string $caddyAdminAddr = null,
        #[Autowire(env: 'default::CADDY_TLS')]
        private ?string $caddyTls = null,
        #[Autowire(env: 'default::DEPLOY_GATEWAY_HOST')]
        private ?string $deployGatewayHost = null,
        private Filesystem $filesystem = new Filesystem(),
    ) {
    }

    public function syncDomains(array $activeDomains, bool $reload = true): void
    {
        $sitesDir = $this->settings->caddySitesPath();
        $this->filesystem->mkdir($sitesDir, 0o755);

        $blocks = [];
        $tlsDirective = null !== $this->caddyTls && '' !== trim($this->caddyTls) ? "\n\t".trim($this->caddyTls) : '';

        foreach ($activeDomains as $domain) {
            $env = $domain->environment();
            if (!$env->isEnabled()) {
                continue;
            }

            $upstream = $this->resolveUpstream($domain);
            $host = $domain->domain();

            if ('' !== $tlsDirective) {
                $blocks[] = <<<CADDY
                    http://{$host} {
                    	encode zstd br gzip
                    	reverse_proxy {$upstream}
                    }

                    https://{$host} {{$tlsDirective}
                    	encode zstd br gzip
                    	reverse_proxy {$upstream}
                    }
                    CADDY;
            } else {
                $site = str_contains($host, '://') ? $host : 'http://'.$host;
                $blocks[] = <<<CADDY
                    {$site} {
                    	encode zstd br gzip
                    	reverse_proxy {$upstream}
                    }
                    CADDY;
            }
        }

        $content = "# Auto-generated by gickers.sh Deploy Engine. Do not edit manually.\n\n".implode("\n\n", $blocks)."\n";
        $targetFile = $sitesDir.'/deployed_domains.caddy';
        $this->filesystem->dumpFile($targetFile, $content);

        if ($reload) {
            $this->reloadCaddy();
        }
    }

    public function smokeTest(DeployDomain $domain): ?int
    {
        $upstreamUrl = sprintf('http://%s/', $this->resolveUpstream($domain));

        try {
            $response = $this->httpClient->request('GET', $upstreamUrl, [
                'headers' => [
                    'Host' => $domain->domain(),
                    'User-Agent' => 'CodesSh-SmokeTest/1.0',
                ],
                'timeout' => 4.0,
                'max_redirects' => 0,
            ]);

            return $response->getStatusCode();
        } catch (\Throwable) {
            return null;
        }
    }

    private function resolveUpstream(DeployDomain $domain): string
    {
        if (null !== $this->deployGatewayHost && '' !== trim($this->deployGatewayHost)) {
            return sprintf('%s:%d', trim($this->deployGatewayHost), $domain->gatewayPort());
        }

        return sprintf('%s:%d', $domain->environment()->proxyAlias($domain->serviceName()), $domain->targetPort());
    }

    private function reloadCaddy(): void
    {
        $finder = new ExecutableFinder();
        $binary = $finder->find('frankenphp') ?? $finder->find('caddy');
        if (null === $binary) {
            return;
        }

        $caddyfile = $this->projectDir.'/Caddyfile';
        if (!is_file($caddyfile)) {
            return;
        }

        $cmd = [$binary, 'reload'];
        if (null !== $this->caddyAdminAddr && '' !== trim($this->caddyAdminAddr)) {
            $cmd[] = '--address';
            $cmd[] = trim($this->caddyAdminAddr);
        }
        $cmd[] = '--config';
        $cmd[] = $caddyfile;

        $proc = new Process($cmd, $this->projectDir, [
            'SOFT_SERVE_DATA_PATH' => $this->settings->dataPath,
        ]);
        $proc->setTimeout(10);
        $proc->run();

        if (null !== $this->caddyAdminAddr && '' !== trim($this->caddyAdminAddr) && !$proc->isSuccessful()) {
            throw new \RuntimeException(sprintf(
                'Failed to reload Caddy reverse proxy at %s: %s',
                $this->caddyAdminAddr,
                trim($proc->getErrorOutput() ?: $proc->getOutput())
            ));
        }
    }
}
